def tr(language: Language | str | None, key: str, **values: Any) -> str:
    try:
        resolved = Language(language) if language is not None else DEFAULT_LANGUAGE
    except ValueError:
        resolved = DEFAULT_LANGUAGE
    return TRANSLATIONS[resolved][key].format(**values)


def translated_values(key: str) -> frozenset[str]:
    return frozenset(catalog[key] for catalog in TRANSLATIONS.values())
